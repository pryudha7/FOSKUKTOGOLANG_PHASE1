const { chromium } = require("playwright-core");
const out = process.argv[2];
(async () => {
  const browser = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe" });
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 }, extraHTTPHeaders: { "X-Forwarded-Proto": "https" } });
  const page = await ctx.newPage();
  await page.goto("http://localhost:13000/PRWebDB1");
  await page.fill('input[name="username"]', "pebrianto");
  await page.fill('input[name="password"]', "Rahasia#1");
  await page.click('button[type="submit"]');
  await page.waitForURL("**/app/fossyariah");
  await page.waitForSelector("nav");
  const bg = (name) => page.getByRole("button", { name, exact: true }).evaluate((el) => getComputedStyle(el).backgroundColor);
  await page.hover("nav"); await page.waitForTimeout(300);
  const r = {};
  r.toolsNormal = await bg("Tools");
  await page.hover("text=Gold Monitoring"); await page.waitForTimeout(150);
  r.goldHover = await bg("Gold Monitoring");
  r.goldWeight = await page.getByRole("button", { name: "Gold Monitoring", exact: true }).evaluate((el) => getComputedStyle(el).fontWeight + " " + getComputedStyle(el).color);
  await page.getByRole("button", { name: "Create", exact: true }).click(); await page.waitForTimeout(150);
  r.createOpen = await page.getByRole("button", { name: "Create", exact: true }).getAttribute("aria-expanded");
  await page.screenshot({ path: `${out}/fix-expanded.png` });
  await page.mouse.move(800, 400); await page.waitForTimeout(300);
  r.collapsedCreateExpanded = await page.locator("nav button[aria-expanded]").first().getAttribute("aria-expanded");
  await page.hover("nav"); await page.waitForTimeout(300);
  r.reexpandedCreateOpen = await page.getByRole("button", { name: "Create", exact: true }).getAttribute("aria-expanded");
  console.log(JSON.stringify(r, null, 1));
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
